#!/usr/bin/env python3
import pathlib
import sys
import zipfile

# Synthetic X1 patch. It programs AY channel A, both possible YM2151 boards,
# enables interrupts and then idles. RST 38h returns from IM1 interrupts.
code = bytearray(0x140)
code[0x38] = 0xED
code[0x39] = 0x4D  # RETI
program = bytes([
    0xF3,                         # DI
    0x31, 0xFE, 0xFF,             # LD SP,FFFE
    0x01, 0x00, 0x1B, 0x3E, 0x00, 0xED, 0x79,  # AY address 0
    0x01, 0x00, 0x1C, 0x3E, 0x20, 0xED, 0x79,  # AY period low
    0x01, 0x00, 0x1B, 0x3E, 0x08, 0xED, 0x79,  # AY address 8
    0x01, 0x00, 0x1C, 0x3E, 0x0F, 0xED, 0x79,  # AY volume
    0x01, 0x00, 0x07, 0x3E, 0x08, 0xED, 0x79,  # OPM1 address
    0x01, 0x01, 0x07, 0x3E, 0x78, 0xED, 0x79,  # OPM1 key on
    0x01, 0x04, 0x07, 0x3E, 0x08, 0xED, 0x79,  # changed-address OPM2 address
    0x01, 0x05, 0x07, 0x3E, 0x79, 0xED, 0x79,  # changed-address OPM2 key on
    0xFB, 0x76, 0x18, 0xFD,       # EI; HALT; JR HALT
])
code[0x100:0x100 + len(program)] = program

output = pathlib.Path(sys.argv[1])
output.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
    archive.writestr("PATCH", code)
    archive.writestr("SONG", bytes(range(64)))
    archive.writestr("PORTS", b"X1IO")
